test("Отмена срока, сомнение, чужие слова, новый срок и вопрос без исполнителя",()=>{
  const run=lines=>ZuConversation.prepare(lines.map((text,i)=>({id:i,start:i*4,end:i*4+3,text})));
  const changed=run(["Мы договорились сдать в пятницу.","Пятницу отменяем. Новую дату ещё не выбрали."]);
  assert.deepEqual(changed.map(x=>x.kind),["superseded","changes"]);
  assert.equal(changed[1].references[0].text,changed[0].text);
  const weak=run(["Я не помню, договорились ли мы о пятнице.","Они сказали, что согласовали среду.","Если решили, сообщите.","Вроде согласовали встречу.","Ещё не решили, кто пойдёт."]);
  assert.ok(weak.every(x=>x.kind==="speech"));
  const agreement=run(["Обсудим в пятницу.","Давайте в четверг.","Согласен, встречаемся в четверг.","Кто пришлёт макет?"]);
  assert.deepEqual(agreement.map(x=>x.kind),["proposal","proposal","decisions","questions"]);
  assert.deepEqual(agreement[2].references,[agreement[1]]);
  assert.equal(agreement[3].assignee,undefined);
  const unrelated=run(["Согласовали встречу в пятницу.","Договорились сдать отчёт в пятницу.","Встречу в пятницу отменили."]);
  assert.deepEqual(unrelated.map(x=>x.kind),["superseded","decisions","changes"]);
  const excluded=run(["Решили собрать плату.","Решение отменять не будем.","Если отменим, сообщу."]);
  assert.equal(excluded.filter(x=>x.kind==="decisions").length,1);
});

