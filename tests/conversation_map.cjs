test("Карта сохраняет дословную опору и не превращает вопрос или отрицание в решение", () => {
  const source = ["Решили оставить два микрофона.", "Мы не решили, куда ставить плату.", "Если договорились, сообщи.", "Мы договорились?", "Я пришлю чертёж.", "Решили убрать экран."];
  const rows = source.map((text,i)=>({text, start:i+.1, end:i+1, needs_review:i===5}));
  const ready = ZuConversation.prepare([...rows,{text:"без времени",start:null,end:6}]);
  assert.deepEqual(ready.map(x=>x.text),source);
  assert.deepEqual(ready.map(x=>x.kind),["decisions","speech","speech","questions","actions","review"]);
  const long = Array.from({length:1800},(_,i)=>({text:i%30===0?"Теперь о расписании.":"Речь "+i,start:i*3,end:i*3+2}));
  const groups = ZuConversation.topicGroups(ZuConversation.prepare(long));
  assert.ok(groups.length>=30);
  assert.deepEqual(groups.flatMap(g=>g.rows.map(x=>x.start)),long.map(s=>s.start));
});

