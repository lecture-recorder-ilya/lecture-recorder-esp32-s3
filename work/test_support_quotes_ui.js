const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../outputs/recorder/lecture_workflow.js'),'utf8');
const first=source.indexOf('  function summary(){'),last=source.indexOf('  function show(tab)',first);
assert(first>=0&&last>first);
const make=(tag,text)=>({tag,text:text||'',children:[],append(...items){this.children.push(...items)}});
const text=node=>node.text+node.children.map(text).join(' ');
const buttons=node=>node.children.flatMap(child=>[...(child.tag==='button'?[child]:[]),...buttons(child)]);
const report={draft:true,draft_kind:'support_quotes',overview:'Черновик. Сверь цитаты со звуком.',summary:['Значение не равно пяти.'],summary_evidence:[{quote:'Значение не равно пяти.',start:1.125}],homework:[{task:'Не показывать в черновике'}]};
const seeks=[];
const context={report,node:make,clock:String,card:{},seek:(_,start)=>seeks.push(start),pending:()=>0,name:'lecture.wav'};
vm.createContext(context);vm.runInContext(source.slice(first,last)+'\nthis.renderSummary=summary;',context);
let rendered=context.renderSummary();
assert(text(rendered).includes('Опорные цитаты · черновик'));
assert(text(rendered).includes(report.summary[0]));
assert(!text(rendered).includes('Что задано'));
buttons(rendered)[0].onclick();assert.deepEqual(seeks,[1.125]);
report.draft_kind=undefined;rendered=context.renderSummary();
assert(text(rendered).includes('Готовим конспект'));
assert(!text(rendered).includes(report.summary[0]));
report.draft=false;report.homework=[];report.overview='Итоговый конспект';
rendered=context.renderSummary();
assert(text(rendered).includes('Итоговый конспект'));
assert(!text(rendered).includes('Опорные цитаты · черновик'));
console.log('PASS: current reader summary tab, explicit draft, exact seek, hidden homework and final report');
